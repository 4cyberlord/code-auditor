import assert from "node:assert/strict";
import {codeLineDiff} from "../src/lib/codeLineDiff.ts";
let output=codeLineDiff("def solve(nums):\n    return sum(nums)\n","def solve(nums):\n    return len(nums)\n");
assert.equal(output.filter(x=>x.kind==="removed").length,1);
assert.equal(output.filter(x=>x.kind==="added").length,1);
assert.equal(output.find(x=>x.kind==="removed")?.text,"    return sum(nums)");
assert.equal(output.find(x=>x.kind==="added")?.text,"    return len(nums)");
assert.equal(output.find(x=>x.kind==="removed")?.beforeLine,2);
assert.equal(output.find(x=>x.kind==="added")?.afterLine,2);
assert.equal(output[0].kind,"context");
assert.deepEqual(codeLineDiff("x\n","x\n").map(x=>x.kind),["context","context"]);
output=codeLineDiff("a\nb\nc","a\ninsert\nb\nc");
assert.deepEqual(output.map(x=>x.kind),["context","added","context","context"]);
assert.equal(output.find(x=>x.kind==="added")?.afterLine,2);
output=codeLineDiff("a\nremoved\nb","a\nb");
assert.deepEqual(output.map(x=>x.kind),["context","removed","context"]);
const stressBefore=Array.from({length:1550},(_,i)=>"before "+i).join("\n");
const stressAfter=Array.from({length:1550},(_,i)=>"after "+i).join("\n");
output=codeLineDiff(stressBefore,stressAfter);
assert.equal(output.length,3100,"Large changes must avoid quadratic memory yet preserve all lines");
assert.equal(output.filter(x=>x.kind==="removed").length,1550);
assert.equal(output.filter(x=>x.kind==="added").length,1550);
console.log("PASS: red/green Council line diff and bounded large-source fallback");
